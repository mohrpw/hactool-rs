#[inline]
fn is_zero(buf: &[u8]) -> bool {
    buf.iter().all(|&b| b == 0)
}

fn generate_kek(
    dst: &mut [u8; 0x10],
    src: &[u8; 0x10],
    master_key: &[u8; 0x10],
    kek_seed: &[u8; 0x10],
    key_seed: Option<&[u8; 0x10]>,
) {
    let mut kek = [0u8; 0x10];
    let mut src_kek = [0u8; 0x10];

    let mut master_ctx = AesCtx::new(master_key, 0x10, AesMode::Ecb);
    master_ctx.decrypt(kek_seed, &mut kek);

    let mut kek_ctx = AesCtx::new(&kek, 0x10, AesMode::Ecb);
    kek_ctx.decrypt(src, &mut src_kek);

    if let Some(kseed) = key_seed {
        let mut key_ctx = AesCtx::new(&src_kek, 0x10, AesMode::Ecb);
        key_ctx.decrypt(kseed, dst);
    } else {
        *dst = src_kek;
    }
}

pub fn pki_derive_keys(keyset: &mut NcaKeyset) {
    let mut cmac = [0u8; 0x10];

    // 1. Derive keyblob keys
    for i in 0..0x6 {
        if is_zero(&keyset.secure_boot_key)
            || is_zero(&keyset.tsec_key)
            || is_zero(&keyset.keyblob_key_sources[i])
        {
            continue;
        }
        let mut sbk_ctx = AesCtx::new(&keyset.secure_boot_key, 0x10, AesMode::Ecb);
        let mut tsec_ctx = AesCtx::new(&keyset.tsec_key, 0x10, AesMode::Ecb);
        tsec_ctx.decrypt(&keyset.keyblob_key_sources[i], &mut keyset.keyblob_keys[i]);
        sbk_ctx.decrypt_in_place(&mut keyset.keyblob_keys[i]);

        if is_zero(&keyset.keyblob_mac_key_source) {
            continue;
        }
        let mut mac_gen_ctx = AesCtx::new(&keyset.keyblob_keys[i], 0x10, AesMode::Ecb);
        mac_gen_ctx.decrypt(&keyset.keyblob_mac_key_source, &mut keyset.keyblob_mac_keys[i]);
        if i == 0 && !is_zero(&keyset.per_console_key_source) {
            mac_gen_ctx.decrypt(&keyset.per_console_key_source, &mut keyset.device_key);
        }
    }

    // 2. Decrypt keyblobs
    for i in 0..0x6 {
        if is_zero(&keyset.keyblob_keys[i])
            || is_zero(&keyset.keyblob_mac_keys[i])
            || is_zero(&keyset.encrypted_keyblobs[i])
        {
            continue;
        }
        aes_calculate_cmac(
            &mut cmac,
            &keyset.encrypted_keyblobs[i][0x10..0xB0],
            &keyset.keyblob_mac_keys[i],
        );
        if cmac != keyset.encrypted_keyblobs[i][0..0x10] {
            eprintln!(
                "[ WARN ] Keyblob MAC {:02x} is invalid. Are SBK/TSEC key correct?",
                i
            );
            continue;
        }
        let mut keyblob_ctx = AesCtx::new(&keyset.keyblob_keys[i], 0x10, AesMode::Ctr);
        keyblob_ctx.set_iv(&keyset.encrypted_keyblobs[i][0x10..0x20]);
        keyblob_ctx.decrypt(
            &keyset.encrypted_keyblobs[i][0x20..0xB0],
            &mut keyset.keyblobs[i],
        );
    }

    // 3. Populate package1_keys & master_keks from keyblobs
    for i in 0..0x6 {
        if !is_zero(&keyset.keyblobs[i][0x80..0x90]) {
            keyset.package1_keys[i].copy_from_slice(&keyset.keyblobs[i][0x80..0x90]);
        }
        if !is_zero(&keyset.keyblobs[i][0x00..0x10]) {
            keyset.master_keks[i].copy_from_slice(&keyset.keyblobs[i][0x00..0x10]);
        }
    }

    // 4. Derive 6.2.0+ TSEC root keys & package1 keys
    for i in 0x6..0x20 {
        if is_zero(&keyset.tsec_auth_signatures[i - 6]) {
            continue;
        }
        if !is_zero(&keyset.tsec_root_kek) {
            let mut tsec_root_ctx = AesCtx::new(&keyset.tsec_root_kek, 0x10, AesMode::Ecb);
            tsec_root_ctx.encrypt(
                &keyset.tsec_auth_signatures[i - 6],
                &mut keyset.tsec_root_keys[i - 6],
            );
        }
        if !is_zero(&keyset.package1_mac_kek) {
            let mut pk11_mac_ctx = AesCtx::new(&keyset.package1_mac_kek, 0x10, AesMode::Ecb);
            pk11_mac_ctx.encrypt(
                &keyset.tsec_auth_signatures[i - 6],
                &mut keyset.package1_mac_keys[i],
            );
        }
        if !is_zero(&keyset.package1_kek) {
            let mut pk11_ctx = AesCtx::new(&keyset.package1_kek, 0x10, AesMode::Ecb);
            pk11_ctx.encrypt(
                &keyset.tsec_auth_signatures[i - 6],
                &mut keyset.package1_keys[i],
            );
        }
    }

    // 5. Derive 6.2.0+ master_keks from tsec_root_keys
    for i in 0x6..0x20 {
        let which_tsec_root_key = if i >= 0x8 { 0x8 - 6 } else { i - 6 };
        if is_zero(&keyset.tsec_root_keys[which_tsec_root_key])
            || is_zero(&keyset.master_kek_sources[i])
        {
            continue;
        }
        let mut tsec_root_ctx =
            AesCtx::new(&keyset.tsec_root_keys[which_tsec_root_key], 0x10, AesMode::Ecb);
        tsec_root_ctx.decrypt(&keyset.master_kek_sources[i], &mut keyset.master_keks[i]);
    }

    // 6. Derive master_keks with Mariko keydata
    for i in 0..0x20 {
        if is_zero(&keyset.mariko_kek) || is_zero(&keyset.mariko_master_kek_sources[i]) {
            continue;
        }
        let mut mariko_kek_ctx = AesCtx::new(&keyset.mariko_kek, 0x10, AesMode::Ecb);
        mariko_kek_ctx.decrypt(
            &keyset.mariko_master_kek_sources[i],
            &mut keyset.master_keks[i],
        );
    }

    // 7. Derive master_keys from master_keks
    for i in 0..0x20 {
        if is_zero(&keyset.master_key_source) || is_zero(&keyset.master_keks[i]) {
            continue;
        }
        let mut master_gen_ctx = AesCtx::new(&keyset.master_keks[i], 0x10, AesMode::Ecb);
        master_gen_ctx.decrypt(&keyset.master_key_source, &mut keyset.master_keys[i]);
    }

    // 8. Derive KAEKs, titlekeks, package2_keys, header_key, sd_card_keys, save_mac_key
    for i in 0..0x20 {
        if is_zero(&keyset.master_keys[i]) {
            continue;
        }
        let master_key = keyset.master_keys[i];
        let mut master_ctx = AesCtx::new(&master_key, 0x10, AesMode::Ecb);

        if !is_zero(&keyset.key_area_key_application_source) {
            let src = keyset.key_area_key_application_source;
            let kek_gen = keyset.aes_kek_generation_source;
            let key_gen = keyset.aes_key_generation_source;
            generate_kek(
                &mut keyset.key_area_keys[i][0],
                &src,
                &master_key,
                &kek_gen,
                Some(&key_gen),
            );
        }
        if !is_zero(&keyset.key_area_key_ocean_source) {
            let src = keyset.key_area_key_ocean_source;
            let kek_gen = keyset.aes_kek_generation_source;
            let key_gen = keyset.aes_key_generation_source;
            generate_kek(
                &mut keyset.key_area_keys[i][1],
                &src,
                &master_key,
                &kek_gen,
                Some(&key_gen),
            );
        }
        if !is_zero(&keyset.key_area_key_system_source) {
            let src = keyset.key_area_key_system_source;
            let kek_gen = keyset.aes_kek_generation_source;
            let key_gen = keyset.aes_key_generation_source;
            generate_kek(
                &mut keyset.key_area_keys[i][2],
                &src,
                &master_key,
                &kek_gen,
                Some(&key_gen),
            );
        }

        if !is_zero(&keyset.titlekek_source) {
            master_ctx.decrypt(&keyset.titlekek_source, &mut keyset.titlekeks[i]);
        }

        if !is_zero(&keyset.package2_key_source) {
            master_ctx.decrypt(&keyset.package2_key_source, &mut keyset.package2_keys[i]);
        }

        if i == 0 && !is_zero(&keyset.header_kek_source) && !is_zero(&keyset.header_key_source) {
            let mut header_kek = [0u8; 0x10];
            generate_kek(
                &mut header_kek,
                &keyset.header_kek_source,
                &master_key,
                &keyset.aes_kek_generation_source,
                Some(&keyset.aes_key_generation_source),
            );
            let mut header_ctx = AesCtx::new(&header_kek, 0x10, AesMode::Ecb);
            header_ctx.decrypt(&keyset.header_key_source, &mut keyset.header_key);
        }

        if i == 0 && !is_zero(&keyset.sd_card_kek_source) {
            let mut sd_kek = [0u8; 0x10];
            generate_kek(
                &mut sd_kek,
                &keyset.sd_card_kek_source,
                &master_key,
                &keyset.aes_kek_generation_source,
                Some(&keyset.aes_key_generation_source),
            );
            let mut sd_ctx = AesCtx::new(&sd_kek, 0x10, AesMode::Ecb);
            for k in 0..2 {
                if !is_zero(&keyset.sd_card_key_sources[k]) {
                    sd_ctx.decrypt(&keyset.sd_card_key_sources[k], &mut keyset.sd_card_keys[k]);
                }
            }
        }

        if i == 0
            && !is_zero(&keyset.save_mac_kek_source)
            && !is_zero(&keyset.save_mac_key_source)
            && !is_zero(&keyset.device_key)
        {
            let src = keyset.save_mac_kek_source;
            let dev_key = keyset.device_key;
            let kek_gen = keyset.aes_kek_generation_source;
            let key_gen = keyset.save_mac_key_source;
            generate_kek(
                &mut keyset.save_mac_key,
                &src,
                &dev_key,
                &kek_gen,
                Some(&key_gen),
            );
        }
    }
}

fn print_key_with_name(key: &[u8], name: &str) {
    if !is_zero(key) {
        print!("{:<32}= ", name);
        for &b in key {
            print!("{:02X}", b);
        }
        println!();
    }
}

fn print_key_with_name_idx(key: &[u8], name: &str, idx: usize) {
    if !is_zero(key) {
        let key_name = format!("{}_{:02x}", name, idx);
        print!("{:<32}= ", key_name);
        for &b in key {
            print!("{:02X}", b);
        }
        println!();
    }
}

