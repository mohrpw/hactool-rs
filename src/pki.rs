pub fn pki_initialize_keyset(keyset: &mut NcaKeyset, variant: KeysetVariant) {
    *keyset = NcaKeyset::default();
    match variant {
        KeysetVariant::Dev => {
            keyset.nca_hdr_fixed_key_moduli = DEV_NCA_HDR_MODULI;
            keyset.acid_fixed_key_moduli = DEV_ACID_MODULI;
            keyset.package2_fixed_key_modulus = DEV_PKG2_MODULUS;
        }
        KeysetVariant::Retail => {
            keyset.nca_hdr_fixed_key_moduli = RETAIL_NCA_HDR_MODULI;
            keyset.acid_fixed_key_moduli = RETAIL_ACID_MODULI;
            keyset.package2_fixed_key_modulus = RETAIL_PKG2_MODULUS;
        }
    }
    pki_derive_keys(keyset);
}

